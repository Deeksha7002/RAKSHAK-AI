export function getTranslation(lang: LanguageCode, key: string): string {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;
  return dict[key] || TRANSLATIONS.en[key] || key;
}

export function speakText(text: string, lang: LanguageCode = 'en') {
  if (!('speechSynthesis' in window)) return;
  window.speechSynthesis.cancel(); // Stop current speech
  const langOpt = SUPPORTED_LANGUAGES.find(l => l.code === lang) || SUPPORTED_LANGUAGES[0];
  const utterance = new SpeechSynthesisUtterance(text);
  utterance.lang = langOpt.speechLang;
  utterance.rate = 0.95; // Slightly slower for clear accessibility
  window.speechSynthesis.speak(utterance);
}
